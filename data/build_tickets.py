def main() -> None:
    lines = []
    for tid, tier, status, created, promised, owner, subject, body, queue, sev, blocked, eng, missing in T:
        record = {
            "id": tid,
            "customer_tier": tier,
            "status": status,
            "created_at": created,
            "promised_update_at": promised,
            "owner": owner,
            "subject": subject,
            "body": body,
            "labels": {
                "queue": queue,
                "severity": sev,
                "blocked": blocked,
                "needs_engineering": eng,
                "missing_diagnostics": missing,
            },
        }
        lines.append(json.dumps(record))
    Path(__file__).with_name("tickets.jsonl").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
